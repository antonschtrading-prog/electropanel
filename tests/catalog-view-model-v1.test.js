'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {makeCards,filterCards,DISPLAY_FIELDS}=require('../catalog-intake/catalog-view-model-v1.js');
test('cards include every staged article',()=>assert.equal(makeCards().length,46));
test('cards use stable SKU ids',()=>assert.ok(makeCards().every(x=>x.id===x.sku)));
test('cards are non-selectable',()=>assert.ok(makeCards().every(x=>!x.selectable)));
test('cards are not engineering approved',()=>assert.ok(makeCards().every(x=>!x.engineeringApproved)));
test('cards contain source URL',()=>assert.ok(makeCards().every(x=>x.sourceUrl?.startsWith('https://'))));
test('cards never borrow product images',()=>assert.ok(makeCards().every(x=>x.imageUrl===null)));
test('cards include all supported categories',()=>assert.deepEqual(Object.keys(DISPLAY_FIELDS),['MCB','RCD','RCBO','METER','RELAY','CONTACTOR']));
test('RCD cards show residual current',()=>assert.ok(makeCards().filter(x=>x.kind==='RCD').every(x=>Object.hasOwn(x.fields,'residualCurrentMa'))));
test('RCBO cards show protected poles',()=>assert.ok(makeCards().filter(x=>x.kind==='RCBO').every(x=>Object.hasOwn(x.fields,'protectedPoles'))));
test('contactor cards show coil frequency',()=>assert.ok(makeCards().filter(x=>x.kind==='CONTACTOR').every(x=>Object.hasOwn(x.fields,'coilFrequencyHz'))));
test('kind filter works',()=>assert.equal(filterCards({kind:'RCBO'}).count,5));
test('maker filter works case-insensitively',()=>assert.equal(filterCards({maker:'abb'}).count,34));
test('SKU search works',()=>assert.equal(filterCards({search:'CDA440D'}).count,1));
test('search is case-insensitive',()=>assert.equal(filterCards({search:'cda440d'}).count,1));
test('missing maker gives zero cards',()=>assert.equal(filterCards({maker:'nonexistent'}).count,0));
test('empty search returns all',()=>assert.equal(filterCards({search:'  '}).count,46));
test('incomplete filter only includes blocked cards',()=>assert.ok(filterCards({onlyIncomplete:true}).cards.every(x=>x.reviewStatus==='BLOCKED'||x.missingRequired.length>0)));
test('filter response is not live catalogue',()=>assert.equal(filterCards().canAddToPanel,false));
test('cards are sorted deterministically',()=>assert.deepEqual(makeCards(),makeCards()));
test('field label for unknown value is explicit dash',()=>assert.ok(makeCards().some(x=>Object.values(x.fieldLabels).includes('—'))));
