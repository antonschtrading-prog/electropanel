'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {handleCatalogueRequest:h}=require('../catalog-intake/catalog-api-v1.js');
test('list returns 46 staging cards',()=>assert.equal(h().count,46));
test('get returns exact article',()=>assert.equal(h({operation:'get',sku:'CDA440D'}).card.sku,'CDA440D'));
test('get is case insensitive',()=>assert.equal(h({operation:'get',sku:'cda440d'}).ok,true));
test('get rejects missing SKU',()=>assert.equal(h({operation:'get'}).error,'SKU_REQUIRED'));
test('get returns explicit not found',()=>assert.equal(h({operation:'get',sku:'FAKE'}).error,'SKU_NOT_FOUND'));
test('find supports protection filter',()=>assert.equal(h({operation:'find',criteria:{kind:'RCBO'}}).count,5));
test('din-fit previews module usage',()=>assert.equal(h({operation:'din-fit',criteria:{kind:'MCB'},availableModules:12}).ok,true));
test('din-fit rejects zero slots',()=>assert.equal(h({operation:'din-fit',availableModules:0}).error,'INVALID_CRITERIA'));
test('summary returns total records',()=>assert.equal(h({operation:'summary'}).articles,46));
test('review returns release bundle',()=>assert.equal(h({operation:'review'}).articles.length,46));
test('unknown operation returns error',()=>assert.equal(h({operation:'write'}).error,'UNKNOWN_OPERATION'));
test('invalid request returns error',()=>assert.equal(h(null).error,'INVALID_REQUEST'));
test('arrays are not valid requests',()=>assert.equal(h([]).error,'INVALID_REQUEST'));
test('invalid numeric criterion returns safe error',()=>assert.equal(h({operation:'find',criteria:{inA:-1}}).error,'INVALID_CRITERIA'));
test('list filters manufacturer',()=>assert.equal(h({operation:'list',filters:{maker:'Hager'}}).count,1));
test('list filters category',()=>assert.equal(h({operation:'list',filters:{kind:'CONTACTOR'}}).count,5));
test('API never enables live panel insertion',()=>assert.equal(h({operation:'list'}).canAddToPanel,false));
test('API returns no write operations',()=>assert.equal(h({operation:'approve'}).ok,false));
test('API is deterministic',()=>assert.deepEqual(h({operation:'get',sku:'A9F74116'}),h({operation:'get',sku:'A9F74116'})));
test('review API blocks automatic integration',()=>assert.equal(h({operation:'review'}).coreIntegrationAllowed,false));
