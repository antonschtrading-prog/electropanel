test("valid project is not installation ready",()=>assert.ok(check().ready_for_installation===false));
test("manufacturer cabinet fit remains unverified",()=>assert.ok(check().manufacturerCabinetFitVerified===false));
test("schema is stable",()=>assert.ok(check().schema==='electropanel.cabinet.delivery.convergence.1'));
test("two placed devices are counted",()=>assert.ok(check().totals.placed===2));
test("two distinct articles are counted",()=>assert.ok(check().totals.articles===2));
test("three occupied modules are counted",()=>assert.ok(check().totals.occupied===3));
test("nine free modules are counted",()=>assert.ok(check().totals.free===9));
test("two rails are retained",()=>assert.ok(check().rails.length===2));
test("first rail occupancy is three",()=>assert.ok(check().rails[0].occupied===3));
test("second rail occupancy is zero",()=>assert.ok(check().rails[1].occupied===0));
test("first rail capacity is six",()=>assert.ok(check().rails[0].capacity===6));
test("second rail free is six",()=>assert.ok(check().rails[1].free===6));
test("two stylized articles are counted",()=>assert.ok(check().totals.imageStylized===2));
test("no reviewed images are fabricated",()=>assert.ok(check().totals.imageReviewed===0));
test("no rejected images are fabricated",()=>assert.ok(check().totals.imageRejected===0));
test("no geometry conflicts are fabricated",()=>assert.ok(check().totals.geometryConflicts===0));
test("two actionable articles are counted",()=>assert.ok(check().totals.actionable===2));
test("review queue has two actionable articles",()=>assert.ok(check().reviewQueue.total===2));
test("device L1 exists",()=>assert.ok(check().rows.some(x=>x.deviceId==='L1')));
test("device L2 exists",()=>assert.ok(check().rows.some(x=>x.deviceId==='L2')));
test("device L1 uses A1",()=>assert.ok(check().rows.find(x=>x.deviceId==='L1').boardSku==='A1'));
test("device L2 uses A2",()=>assert.ok(check().rows.find(x=>x.deviceId==='L2').boardSku==='A2'));
test("BOM SKU equals board SKU for L1",()=>assert.ok(check().rows.find(x=>x.deviceId==='L1').bomSku==='A1'));
test("BOM SKU equals board SKU for L2",()=>assert.ok(check().rows.find(x=>x.deviceId==='L2').bomSku==='A2'));
test("rail index is zero-based",()=>assert.ok(check().rows.find(x=>x.deviceId==='L1').railIndex===0));
test("start module is zero-based",()=>assert.ok(check().rows.find(x=>x.deviceId==='L1').startModule===0));
test("device L2 occupies two modules",()=>assert.ok(check().rows.find(x=>x.deviceId==='L2').modules===2));
test("L2 nominal slot is 36mm",()=>assert.ok(check().rows.find(x=>x.deviceId==='L2').nominalSlotWidthMm===36));
test("L1 body width is 17.5mm",()=>assert.ok(check().rows.find(x=>x.deviceId==='L1').bodyWidthMm===17.5));
test("L2 body width is 35mm",()=>assert.ok(check().rows.find(x=>x.deviceId==='L2').bodyWidthMm===35));
test("L1 front is stylized",()=>assert.ok(check().rows.find(x=>x.deviceId==='L1').frontStatus==='STYLIZED_ONLY'));
test("L2 geometry fits nominal slot",()=>assert.ok(check().rows.find(x=>x.deviceId==='L2').geometryStatus==='DECLARED_WITHIN_SLOT'));
test("rows never imply engineering approval",()=>assert.ok(check().rows.every(x=>x.engineeringApproved===false)));
test("invalid null project blocks",()=>assert.ok(check(null).status==='BLOCKED'));
test("invalid lookup blocks",()=>assert.ok(check(project(),null).status==='BLOCKED'));
test("invalid image resolver blocks",()=>assert.ok(check(project(),lookup,null).status==='BLOCKED'));
test("missing board engine blocks",()=>assert.ok((()=>{const old=global.epDraftBoardPlanV1;global.epDraftBoardPlanV1=null;try{return check().status==='BLOCKED'}finally{global.epDraftBoardPlanV1=old}})()));
test("missing BOM engine blocks",()=>assert.ok((()=>{const old=global.epDraftBomV1;global.epDraftBomV1=null;try{return check().status==='BLOCKED'}finally{global.epDraftBomV1=old}})()));
test("missing capacity engine blocks",()=>assert.ok((()=>{const old=global.epBoardCapacityReviewV1;global.epBoardCapacityReviewV1=null;try{return check().status==='BLOCKED'}finally{global.epBoardCapacityReviewV1=old}})()));
test("missing ledger engine blocks",()=>assert.ok((()=>{const old=global.epFrontEvidenceLedgerV1;global.epFrontEvidenceLedgerV1=null;try{return check().status==='BLOCKED'}finally{global.epFrontEvidenceLedgerV1=old}})()));
test("missing queue engine blocks",()=>assert.ok((()=>{const old=global.epFrontReviewQueueV1;global.epFrontReviewQueueV1=null;try{return check().status==='BLOCKED'}finally{global.epFrontReviewQueueV1=old}})()));
