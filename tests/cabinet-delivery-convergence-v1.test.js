global.epFrontEvidenceLedgerV1=require('../front-evidence-ledger-v1').epFrontEvidenceLedgerV1;
global.epFrontReviewQueueV1=require('../front-review-queue-v1').epFrontReviewQueueV1;
const {epCabinetDeliveryConvergenceV1:run,epCabinetDeliveryConvergenceCsvV1:csv}=require('../cabinet-delivery-convergence-v1');
const project=()=>({railCount:2,railCapacity:6,lines:[{id:'L1',modules:1,catalogSku:'A1'},
 {id:'L2',modules:2,catalogSku:'A2'}],sharedDevices:[]});
