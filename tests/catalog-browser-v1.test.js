'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {buildFacets,buildComparison,buildBrowserSnapshot}=require('../catalog-intake/catalog-browser-v1.js');
test('facets count 46 staged SKUs',()=>assert.equal(buildFacets().articles,46));
test('facets expose six device categories',()=>assert.equal(buildFacets().kinds.length,6));
test('facets show zero meters',()=>assert.equal(buildFacets().kinds.find(x=>x.kind==='METER').count,0));
test('facets show zero relays',()=>assert.equal(buildFacets().kinds.find(x=>x.kind==='RELAY').count,0));
test('facets have zero approved records',()=>assert.equal(buildFacets().approved,0));
test('facets include ABB',()=>assert.ok(buildFacets().makers.includes('ABB')));
test('facets include Hager',()=>assert.ok(buildFacets().makers.includes('Hager')));
test('facets include Schneider',()=>assert.ok(buildFacets().makers.includes('Schneider Electric')));
test('comparison needs two SKUs',()=>assert.equal(buildComparison(['A9F74116']).ok,false));
test('comparison rejects duplicate SKU',()=>assert.equal(buildComparison(['A9F74116','a9f74116']).error,'DUPLICATE_SKU'));
test('comparison rejects unknown SKU',()=>assert.equal(buildComparison(['A9F74116','FAKE']).error,'UNKNOWN_SKU'));
test('comparison preserves null values',()=>assert.ok(buildComparison(['A9F74116','2CDS251001R0164']).rows.some(r=>r.values.includes(null))));
test('comparison never approves substitution',()=>assert.equal(buildComparison(['A9F74116','2CDS251001R0164']).canSubstitute,false));
test('comparison reports mixed device categories',()=>assert.equal(buildComparison(['A9F74116','CDA440D']).mixedKinds,true));
test('comparison reports same category',()=>assert.equal(buildComparison(['A9F74116','2CDS251001R0164']).mixedKinds,false));
test('browser snapshot filters RCD',()=>assert.equal(buildBrowserSnapshot({kind:'RCD'}).count,34));
test('browser snapshot filters Schneider',()=>assert.equal(buildBrowserSnapshot({maker:'Schneider Electric'}).count,11));
test('browser snapshot refuses live insertion',()=>assert.equal(buildBrowserSnapshot().canAddToPanel,false));
test('browser snapshot includes source links',()=>assert.ok(buildBrowserSnapshot().results.every(x=>x.sourceUrl?.startsWith('https://'))));
test('browser snapshot is deterministic',()=>assert.deepEqual(buildBrowserSnapshot({kind:'MCB'}),buildBrowserSnapshot({kind:'MCB'})));
