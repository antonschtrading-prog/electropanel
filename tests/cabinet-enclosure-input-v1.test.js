'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {epCabinetEnclosureInputV1:parse}=require('../cabinet-enclosure-input-v1');
const line='BOX-1; Maker; ART-1; 400; 500; 150; 2';
const run=()=>parse(line);
test('valid line',()=>assert.equal(run().status,'REVIEW_REQUIRED'));
test('one item',()=>assert.equal(run().items.length,1));
test('id',()=>assert.equal(run().items[0].id,'BOX-1'));
test('manufacturer',()=>assert.equal(run().items[0].manufacturer,'Maker'));
test('article',()=>assert.equal(run().items[0].article,'ART-1'));
test('width',()=>assert.equal(run().items[0].usableInterior.widthMm,400));
test('height',()=>assert.equal(run().items[0].usableInterior.heightMm,500));
test('depth',()=>assert.equal(run().items[0].usableInterior.depthMm,150));
test('rails',()=>assert.equal(run().items[0].railCapacity,2));
test('two lines',()=>assert.equal(parse(line+'\nBOX-2;;;;;;').items.length,2));
test('decimal comma',()=>assert.equal(parse('A;;;400,5;500;150;2').items[0].usableInterior.widthMm,400.5));
test('empty width unknown',()=>assert.equal(parse('A;;;;500;150;2').items[0].usableInterior.widthMm,null));
test('empty height unknown',()=>assert.equal(parse('A;;;400;;150;2').items[0].usableInterior.heightMm,null));
test('empty depth unknown',()=>assert.equal(parse('A;;;400;500;;2').items[0].usableInterior.depthMm,null));
test('empty rails unknown',()=>assert.equal(parse('A;;;400;500;150;').items[0].railCapacity,null));
test('empty manufacturer null',()=>assert.equal(parse('A;;B;400;500;150;2').items[0].manufacturer,null));
test('empty article null',()=>assert.equal(parse('A;Maker;;400;500;150;2').items[0].article,null));
test('blank input valid',()=>assert.equal(parse(' ').items.length,0));
test('null blocked',()=>assert.equal(parse(null).status,'BLOCKED'));
test('too large blocked',()=>assert.equal(parse('x'.repeat(20001)).status,'BLOCKED'));
test('bad column count blocked',()=>assert.equal(parse('A;B').status,'BLOCKED'));
test('negative dimension blocked',()=>assert.equal(parse('A;;;-1;500;150;2').status,'BLOCKED'));
test('zero dimension blocked',()=>assert.equal(parse('A;;;0;500;150;2').status,'BLOCKED'));
test('invalid numeric blocked',()=>assert.equal(parse('A;;;hello;500;150;2').status,'BLOCKED'));
test('negative rails blocked',()=>assert.equal(parse('A;;;400;500;150;-1').status,'BLOCKED'));
test('fractional rails blocked',()=>assert.equal(parse('A;;;400;500;150;1,5').status,'BLOCKED'));
test('duplicate id blocked',()=>assert.equal(parse(line+'\n'+line).status,'BLOCKED'));
test('too many lines blocked',()=>assert.equal(parse(Array(101).fill(line).join('\n')).status,'BLOCKED'));
test('valid JSON array',()=>assert.equal(parse('[{"id":"X"}]').items[0].id,'X'));
test('invalid JSON blocked',()=>assert.equal(parse('[bad').status,'BLOCKED'));
test('JSON nonarray blocked',()=>assert.equal(parse('{"id":"X"}').status,'BLOCKED'));
test('JSON duplicate blocked',()=>assert.equal(parse('[{"id":"X"},{"id":"X"}]').status,'BLOCKED'));
test('JSON invalid width blocked',()=>assert.equal(parse('[{"id":"X","usableInterior":{"widthMm":-1}}]').status,'BLOCKED'));
test('JSON unknown dimension allowed',()=>assert.equal(parse('[{"id":"X","usableInterior":null}]').status,'REVIEW_REQUIRED'));
test('JSON invalid rail count blocked',()=>assert.equal(parse('[{"id":"X","railCapacity":2.5}]').status,'BLOCKED'));
test('JSON manufacturer must be text',()=>assert.equal(parse('[{"id":"X","manufacturer":12}]').status,'BLOCKED'));
test('deterministic',()=>assert.deepEqual(run(),run()));
