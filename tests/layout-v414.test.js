'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'..','layout-v414.js'),'utf8');
const {epLegacyLayoutCapacity}=vm.runInNewContext(src+'\n({epLegacyLayoutCapacity})');
function fixture(numberOfCircuits){
 const devices=[{id:'X0',model_sku:'DEMO-SOURCE',rail_id:'DIN-1',start_module:0}];
 for(let i=1;i<=numberOfCircuits;i++){
  devices.push({id:'QF'+i,model_sku:'DEMO-MCB',rail_id:'DIN-1',start_module:2*i});
  devices.push({id:'X'+i,model_sku:'DEMO-LOAD',rail_id:'DIN-1',start_module:2*i+1});
 }
 return {panel:{rails:[{id:'DIN-1',modules:36}],devices},
  catalog:{'DEMO-SOURCE':{modules:2},'DEMO-MCB':{modules:1},'DEMO-LOAD':{modules:2}}};
}
// Expected outputs independently generated by the recovered Python v4.14
// layout_capacity_v414 on examples_v47/apartment_studio_project.json and
// examples_v47/commercial_studio_project.json.
test('apartment example matches v4.14 occupied/free slots and collisions',()=>{
 const p=fixture(3),r=epLegacyLayoutCapacity(p);
 assert.equal(r.occupied_modules,9);
 assert.equal(r.free_modules,27);
 assert.equal(r.total_modules,36);
 assert.deepEqual(Array.from(r.rails[0].free_module_numbers),Array.from({length:27},(_,i)=>i+10));
 assert.deepEqual(Array.from(r.problems,x=>[x.code,x.device_id,x.other_device_id,x.module]),
  [['OVERLAP','QF2','X1',5],['OVERLAP','QF3','X2',7]]);
 assert.equal(r.rails[0].utilization_percent,25);
 assert.equal(r.ready_for_installation,false);
});
test('commercial example matches v4.14 module arithmetic and three overlaps',()=>{
 const r=epLegacyLayoutCapacity(fixture(4));
 assert.equal(r.occupied_modules,11);
 assert.equal(r.free_modules,25);
 assert.equal(r.rails[0].utilization_percent,30.56);
 assert.deepEqual(Array.from(r.problems,x=>[x.device_id,x.module]),
  [['QF2',5],['QF3',7],['QF4',9]]);
});
test('out of bounds reported and safety approvals never fabricated',()=>{
 const p=fixture(3);p.panel.devices[0].start_module=100;
 const r=epLegacyLayoutCapacity(p);
 assert.ok(Array.from(r.problems,x=>x.code).includes('OUT_OF_BOUNDS'));
 assert.equal(r.layout_screen_status,'FAIL');
 assert.equal(r.assembly_space_verified,false);
 assert.equal(r.neutral_bus_verified,false);
 assert.equal(r.thermal_verification,false);
 assert.equal(r.project_sha256,null);
});
test('no original project mutation',()=>{
 const p=fixture(4),before=JSON.stringify(p);
 epLegacyLayoutCapacity(p);
 assert.equal(JSON.stringify(p),before);
});
test('empty-but-valid rail remains draft with full capacity',()=>{
 const p={panel:{rails:[{id:'DIN-X',modules:12}],devices:[]},catalog:{}};
 const r=epLegacyLayoutCapacity(p);
 assert.equal(r.occupied_modules,0);
 assert.equal(r.free_modules,12);
 assert.equal(r.layout_screen_status,'STRUCTURAL_ONLY');
 assert.equal(r.ready_for_installation,false);
});
