'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
global.epDraftBoardPlanV1=require('../draft-board-plan-v1').epDraftBoardPlanV1;
global.epCabinetConnectionProximityV1=require('../cabinet-connection-proximity-v1').epCabinetConnectionProximityV1;
global.epCabinetOptionPreviewV1=require('../cabinet-option-preview-v1').epCabinetOptionPreviewV1;
const {epCabinetCrossRailOptimizeV1:optimize}=require('../cabinet-cross-rail-optimize-v1');
const {epCabinetReflowPreviewV1:preview}=require('../cabinet-reflow-preview-v1');
const {epCabinetOptionDinSvgV1:svg}=require('../cabinet-option-din-svg-v1');
const {epCabinetOptionPreviewCsvV1:csv}=require('../cabinet-option-preview-csv-v1');
const project=()=>({railCount:2,railCapacity:3,lines:[{id:'A',modules:2},{id:'B',modules:2}],
 sharedDevices:[{id:'G',modules:1,circuitIds:['B']}],
 manualLayoutV1:[{deviceId:'A',railIndex:0,startModule:1},{deviceId:'B',railIndex:1,startModule:0}]});
const proposal=()=>optimize(project(),()=>null);
const result=()=>preview(project(),proposal(),()=>null);
test('preview status review',()=>assert.equal(result().status,'REVIEW_REQUIRED'));
test('preview schema',()=>assert.equal(result().schema,'electropanel.cabinet.reflow.preview.1'));
test('preview ready code',()=>assert.equal(result().code,'REFLOW_PREVIEW_READY'));
test('preview has three devices',()=>assert.equal(result().summary.devices,3));
test('preview moved count one',()=>assert.equal(result().summary.moved,1));
test('preview rail change one',()=>assert.equal(result().summary.changedRails,1));
test('preview unchanged count two',()=>assert.equal(result().summary.unchanged,2));
test('preview has two rails',()=>assert.equal(result().rails.length,2));
test('preview original capacity',()=>assert.equal(result().summary.oldCapacity,6));
test('preview new capacity',()=>assert.equal(result().summary.newCapacity,6));
test('preview capacity delta zero',()=>assert.equal(result().summary.capacityDelta,0));
test('preview relation count before one',()=>assert.equal(result().beforeRelations.cross,1));
test('preview relation count after zero',()=>assert.equal(result().afterRelations.cross,0));
test('preview identifies moved G',()=>assert.equal(result().rows.find(r=>r.changed).deviceId,'G'));
test('preview G from first rail',()=>assert.equal(result().rows.find(r=>r.deviceId==='G').fromRail,0));
test('preview G to second rail',()=>assert.equal(result().rows.find(r=>r.deviceId==='G').toRail,1));
test('preview keeps A fixed',()=>assert.equal(result().rows.find(r=>r.deviceId==='A').changed,false));
test('preview keeps B fixed',()=>assert.equal(result().rows.find(r=>r.deviceId==='B').changed,false));
test('preview does not approve engineering',()=>assert.equal(result().engineeringApproved,false));
test('preview not installation ready',()=>assert.equal(result().ready_for_installation,false));
test('preview produces svg',()=>assert.match(svg(result()),/^<svg/));
test('preview svg includes moved G',()=>assert.match(svg(result()),/G — изменено/));
test('preview produces csv',()=>assert.match(csv(result()).csv,/device_id/));
test('preview csv includes G',()=>assert.match(csv(result()).csv,/"G"/));
test('null project blocked',()=>assert.equal(preview(null,proposal(),()=>null).status,'BLOCKED'));
test('null proposal blocked',()=>assert.equal(preview(project(),null,()=>null).status,'BLOCKED'));
test('proposal with no project blocked',()=>assert.equal(preview(project(),{...proposal(),project:null},()=>null).status,'BLOCKED'));
test('blocked proposal blocked',()=>assert.equal(preview(project(),{...proposal(),status:'BLOCKED'},()=>null).status,'BLOCKED'));
test('invalid changes blocked',()=>assert.equal(preview(project(),{...proposal(),changes:null},()=>null).status,'BLOCKED'));
test('changed rail count blocked',()=>assert.equal(preview(project(),{...proposal(),project:{...proposal().project,railCount:3}},()=>null).status,'BLOCKED'));
test('changed capacity blocked',()=>assert.equal(preview(project(),{...proposal(),project:{...proposal().project,railCapacity:4}},()=>null).status,'BLOCKED'));
test('duplicate changes blocked',()=>assert.equal(preview(project(),{...proposal(),changes:[...proposal().changes,...proposal().changes]},()=>null).status,'BLOCKED'));
test('omitted changes blocked',()=>assert.equal(preview(project(),{...proposal(),changes:[]},()=>null).status,'BLOCKED'));
test('wrong from rail blocked',()=>assert.equal(preview(project(),{...proposal(),changes:[{...proposal().changes[0],from:{railIndex:1,startModule:0}}]},()=>null).status,'BLOCKED'));
test('wrong to rail blocked',()=>assert.equal(preview(project(),{...proposal(),changes:[{...proposal().changes[0],to:{railIndex:0,startModule:0}}]},()=>null).status,'BLOCKED'));
test('deterministic output',()=>assert.deepEqual(result(),result()));
test('does not mutate project',()=>{const p=project(),s=JSON.stringify(p);preview(p,proposal(),()=>null);assert.equal(JSON.stringify(p),s)});
test('does not mutate proposal',()=>{const p=proposal(),s=JSON.stringify(p);preview(project(),p,()=>null);assert.equal(JSON.stringify(p),s)});
