'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {epCabinetApparatusGeometryV1:run}=require('../cabinet-apparatus-geometry-v1');
const {epCabinetApparatusGeometryCsvV1:csv}=require('../cabinet-apparatus-geometry-csv-v1');
const preview=()=>({status:'REVIEW_REQUIRED',rows:[
 {deviceId:'A',article:'SKU-A',modules:2,toRail:0,toSlot:0},
 {deviceId:'B',article:null,modules:1,toRail:1,toSlot:0}],
 rails:[{railIndex:0,capacity:6},{railIndex:1,capacity:6}]});
const lookup=id=>id==='SKU-A'?{article:'SKU-A',modules:2,geometry:{widthMm:35,heightMm:85,depthMm:68}}:null;
const result=()=>run({},preview(),lookup);
test('schema',()=>assert.equal(result().schema,'electropanel.cabinet.apparatus.geometry.1'));
test('unknown dimensions status',()=>assert.equal(result().status,'UNKNOWN'));
test('two rows',()=>assert.equal(result().rows.length,2));
test('one fully known',()=>assert.equal(result().summary.knownDimensions,1));
test('one unknown',()=>assert.equal(result().summary.missingDimensions,1));
test('catalog width',()=>assert.equal(result().rows[0].widthMm,35));
test('catalog height',()=>assert.equal(result().rows[0].heightMm,85));
test('catalog depth',()=>assert.equal(result().rows[0].depthMm,68));
test('nominal pitch',()=>assert.equal(result().rows[0].nominalWidthMm,36));
test('unknown width null',()=>assert.equal(result().rows[1].widthMm,null));
test('unknown width basis nominal',()=>assert.equal(result().rows[1].widthBasis,'NOMINAL_MODULE_PITCH'));
test('catalog width basis',()=>assert.equal(result().rows[0].widthBasis,'CATALOG'));
test('rail span',()=>assert.equal(result().summary.railWidths[0].nominalSpanMm,108));
test('rail used span',()=>assert.equal(result().summary.railWidths[0].usedNominalSpanMm,36));
test('max depth',()=>assert.equal(result().summary.maxKnownDepthMm,68));
test('max height',()=>assert.equal(result().summary.maxKnownHeightMm,85));
test('no approval',()=>assert.equal(result().engineeringApproved,false));
test('no fit confirmation',()=>assert.equal(result().confirmedFit,false));
test('complete catalog dimensions review',()=>assert.equal(run({},preview(),id=>id==='SKU-A'?lookup(id):null).status,'UNKNOWN'));
test('width too large blocked',()=>assert.equal(run({},preview(),()=>({modules:2,widthMm:37})).status,'BLOCKED'));
test('height band exceeded blocked',()=>assert.equal(run({},preview(),lookup,{mountingBandMm:80}).status,'BLOCKED'));
test('depth limit exceeded blocked',()=>assert.equal(run({},preview(),lookup,{depthLimitMm:60}).status,'BLOCKED'));
test('height within band',()=>assert.equal(run({},preview(),lookup,{mountingBandMm:90}).status,'UNKNOWN'));
test('depth within limit',()=>assert.equal(run({},preview(),lookup,{depthLimitMm:70}).status,'UNKNOWN'));
test('wrong catalog modules blocked',()=>assert.equal(run({},preview(),()=>({modules:3})).status,'BLOCKED'));
test('wrong catalog article blocked',()=>assert.equal(run({},preview(),()=>({article:'OTHER',modules:2})).status,'BLOCKED'));
test('invalid width blocked',()=>assert.equal(run({},preview(),()=>({modules:2,widthMm:-1})).status,'BLOCKED'));
test('invalid height blocked',()=>assert.equal(run({},preview(),()=>({modules:2,heightMm:NaN})).status,'BLOCKED'));
test('invalid depth blocked',()=>assert.equal(run({},preview(),()=>({modules:2,depthMm:Infinity})).status,'BLOCKED'));
test('null project blocked',()=>assert.equal(run(null,preview(),lookup).status,'BLOCKED'));
test('null preview blocked',()=>assert.equal(run({},null,lookup).status,'BLOCKED'));
test('blocked preview blocked',()=>assert.equal(run({},{...preview(),status:'BLOCKED'},lookup).status,'BLOCKED'));
test('null settings blocked',()=>assert.equal(run({},preview(),lookup,null).status,'BLOCKED'));
test('unknown settings blocked',()=>assert.equal(run({},preview(),lookup,{brand:'X'}).status,'BLOCKED'));
test('pitch under range blocked',()=>assert.equal(run({},preview(),lookup,{modulePitchMm:14}).status,'BLOCKED'));
test('pitch above range blocked',()=>assert.equal(run({},preview(),lookup,{modulePitchMm:26}).status,'BLOCKED'));
test('custom pitch',()=>assert.equal(run({},preview(),lookup,{modulePitchMm:20}).rows[0].nominalWidthMm,40));
test('duplicate device blocked',()=>{const p=preview();p.rows.push({...p.rows[0]});assert.equal(run({},p,lookup).status,'BLOCKED')});
test('invalid slot blocked',()=>{const p=preview();p.rows[0].toSlot=-1;assert.equal(run({},p,lookup).status,'BLOCKED')});
test('lookup failure unknown',()=>assert.equal(run({},preview(),()=>{throw Error('offline')}).status,'UNKNOWN'));
test('deterministic',()=>assert.deepEqual(result(),result()));
test('does not mutate preview',()=>{const p=preview(),s=JSON.stringify(p);run({},p,lookup);assert.equal(JSON.stringify(p),s)});
test('CSV has header',()=>assert.match(csv(result()).csv,/catalog_width_mm/));
test('CSV includes known width',()=>assert.match(csv(result()).csv,/"35"/));
test('CSV has unknown blanks',()=>assert.match(csv(result()).csv,/""/));
test('CSV does not approve fit',()=>assert.match(csv(result()).csv,/"NO"/));
test('CSV blocks null',()=>assert.equal(csv(null).status,'BLOCKED'));
test('CSV blocks geometry conflicts',()=>assert.equal(csv(run({},preview(),lookup,{depthLimitMm:60})).status,'BLOCKED'));
test('CSV deterministic',()=>assert.deepEqual(csv(result()),csv(result())));
test('CSV retains row count',()=>assert.equal(csv(result()).rows,2));
test('CSV includes UTF8 BOM',()=>assert.equal(csv(result()).csv.charCodeAt(0),65279));
test('CSV sanitizes spreadsheet formula',()=>{const p=preview();p.rows[0].deviceId='=SUM(1,2)';const s=csv(run({},p,lookup)).csv;assert.match(s,/"'=SUM/);});
